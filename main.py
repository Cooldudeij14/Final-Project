screen = pygame.display.set_mode((screen_width, screen_height))
clock = pygame.time.Clock()

# Set up fonts 
font_large = pygame.font.SysFont("Arial", 40, bold=True)
font_small = pygame.font.SysFont("Arial", 24)
font_msg = pygame.font.SysFont("Arial", 50, bold=True)

keys = [pygame.K_z, pygame.K_x, pygame.K_c, pygame.K_v, pygame.K_b, pygame.K_n, pygame.K_m]
lane_keys = ['Z', 'X', 'C', 'V', 'B', 'N', 'M']
key_labels = [font_large.render(k, True, white) for k in lane_keys]

flash_surf = pygame.Surface((lane_width, screen_height), pygame.SRCALPHA)
flash_surf.fill((255, 255, 255, 40))

notes = []
score = 0
streak = 0
multiplier = 1
high_score = 0
lane_flashes = [0] * 7
feedback_msg = ""
feedback_timer = 0
feedback_color = white
game_started = False


button_rect = pygame.Rect(screen_width // 2 - 100, screen_height // 2 - 50, 200, 100)
button_text = font_large.render("START", True, (0, 255, 0))


running = True
while running:
    
    for event in pygame.event.get():
        if event.type == pygame.QUIT:
            running = False

        elif not game_started:
            if event.type == pygame.MOUSEBUTTONDOWN:
                if button_rect.collidepoint(event.pos):
                    game_started = True
                    time.sleep(2)
                    pygame.mixer.music.play()

        elif event.type == pygame.KEYDOWN:
            
            if event.key in keys:
                clicked_lane = keys.index(event.key)
                lane_flashes[clicked_lane] = 6
                hit_detected = False
                
                
                for note in notes[:]:
                    if note.lane == clicked_lane and abs(note.y - Hitzone) < Hit:
                        notes.remove(note)
                        streak += 1
                        if streak % 10 == 0:
                            multiplier = 1 + (streak // 10) * 0.5
                        score += int(25 * multiplier)
                        feedback_msg = "HIT!"
                        feedback_color = (0, 255, 0)
                        feedback_timer = 20
                        hit_detected = True
                        break
                
                if not hit_detected:
                    
                    feedback_msg = "MISS!"
                    feedback_color = (255, 0, 0)
                    score -= 10
                    streak = 0
                    feedback_timer = 20

    if game_started:
        current_time = pygame.mixer.music.get_pos()

        while song_chart and current_time >= (song_chart[0][0] - 1200 - lead_time):
            target_hit_time, lane = song_chart.pop(0)
            notes.append(Note(lane, target_hit_time - 1200, lane_width, note_height, colors, X, Hitzone, note_speed, speed_multiplier, fps, white))

        for note in notes[:]:
            note.update(current_time)
            if note.y > screen_height:
                notes.remove(note)
                score -= 10
                streak = 0
                feedback_msg = "MISS!"
                feedback_color = (255, 0, 0)
                feedback_timer = 20

    screen.fill(black)

    pygame.draw.rect(screen, purple, (X, Hitzone, lane_width * 7, 60))

    for i in range(7):
        lx = X + (i * lane_width)
        if lane_flashes[i] > 0:
            screen.blit(flash_surf, (lx, 0))
            lane_flashes[i] -= 1
        pygame.draw.rect(screen, white, (lx + 5, Hitzone, lane_width - 10, 60), 3)

    for note in notes:
        note.draw(screen)

    screen.blit(font_small.render(f"SCORE: {score}", True, white), (20, 20))
    screen.blit(font_small.render(f"STREAK: {streak}", True, white), (20, 50))
    screen.blit(font_small.render(f"MULTIPLIER: {multiplier:.1f}x", True, white), (20, 80))
    screen.blit(font_small.render(f"HIGH SCORE: {max(score, high_score)}", True, (255, 215, 0)), (screen_width - 250, 20))
    
    if score > high_score:
        high_score = score
    

    if feedback_timer > 0:
        msg_surf = font_msg.render(feedback_msg, True, feedback_color)
        screen.blit(msg_surf, ((screen_width - msg_surf.get_width()) // 2, screen_height // 2))
        feedback_timer -= 1

    if not game_started:
        pygame.draw.rect(screen, white, button_rect, border_radius=10)
        screen.blit(button_text, button_text.get_rect(center=button_rect.center))

    # Check if game ended and score >= 15000 for speed 2x restart
    if game_started and not pygame.mixer.music.get_busy():
        if score >= 15000:
            # Restart at 2x speed
            speed_multiplier = 3
            song_chart.clear()
            song_chart.extend(song_chart_original)
            notes.clear()
            score = 0
            streak = 0
            multiplier = 1
            lane_flashes = [0] * 7
            feedback_msg = ""
            feedback_timer = 0
            game_started = False
        else:
            game_started = False

    pygame.display.flip()
    clock.tick(fps)

pygame.quit()